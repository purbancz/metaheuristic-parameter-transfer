ROOT = os.path.dirname(os.path.dirname(PT))                  # repository root
TAB, OUT_T = os.path.join(PT, "tables"), os.path.join(HERE, "tables")
os.makedirs(OUT_T, exist_ok=True)
NAME = dict(pd.read_csv(os.path.join(HERE, "names.csv"))[["roster_name", "short_name"]].values)


def tab(name):
    return pd.read_csv(os.path.join(TAB, name))


def short(a):
    return NAME[a]


def tex_escape(s):
    return (str(s).replace("\\", r"\textbackslash{}").replace("%", r"\%").replace("&", r"\&")
            .replace("_", r"\_").replace("#", r"\#"))


def f(v, nd=2):
    if isinstance(v, (bool, np.bool_)):
        return "yes" if v else "no"
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "--"
    if isinstance(v, (int, np.integer)):
        return f"{int(v):,}".replace(",", "{,}")
    if isinstance(v, (float, np.floating)):
        return f"{v:.{nd}f}"
    return tex_escape(v)


# Table 6 prints the declared label "no Stage 2 effect" as "no effect in main comparison"; the CSVs keep the declared label
ARROW = {"C<-S": r"C$\leftarrow$S", "S<-C": r"S$\leftarrow$C"}


def write_tex(name, header, rows, spec, size=r"\footnotesize"):
    body = [" & ".join(r) + r" \\" for r in rows]
    txt = "\n".join(["% generated by build_ola.py - do not edit", r"\begingroup" + size, r"\setlength{\tabcolsep}{3pt}",
                     r"\begin{tabular}{" + spec + "}", r"\toprule", " & ".join(header) + r" \\", r"\midrule", *body,
                     r"\bottomrule", r"\end{tabular}", r"\endgroup", ""])
    with open(os.path.join(OUT_T, name), "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write(txt)


